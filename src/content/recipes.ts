import type { Values } from '../dims/types';

/*
 * 可执行配方：一组维度选项的组合，能在场景里产生明确效果。
 * 每套配方写清楚：想要的画面特征、先调哪几项、和相邻配方的区别、已实现与缺口。
 * 光照/时段的变奏不单独计为风格。
 */

/*
 * 配方图库的字段（docs/workbench-redesign.md §1.3 / §2 F1 / §7，轨道 C）：
 *   category 6 个分类（芯片短名见 taxonomy.ts）；kind 风格 = 图库里一张卡，变体 = 父配方配方卡里的芯片，叠加 = 能叠到任何配方上的一层；
 *   short 卡片名（≤8 字）；bullets 画框下配方卡的 3 条看点（每条 ≤12 字，挂一个参数：悬停闪、点击跳过去）；
 *   showcase 缩略图和「在 X 场景最好看」用的场景（scene2d = 2D 场景上线后改用的环境 id，F 轨道交付后自动切换）；
 *   games 像这些游戏（案例 id，src/content/cases）；uiSkins 配套 UI 皮肤（uiSpec 的 fromArt 没有这个配方时用）；
 *   uiFamilies 配套 UI 家族（复制提示词取它的语法；不写时按家族的 artPairing 反查）；overlay 叠加时只写的那几个键。
 */
export type RecipeCategory = 'pixel' | 'paint' | 'east' | 'flat' | 'form' | 'light';
export type RecipeKind = 'style' | 'variant' | 'overlay';
export interface RecipeBullet { text: string; param: string }
export interface RecipeShowcase { scene: string; overrides?: Values; scene2d?: string }

export interface Recipe {
  id: string;
  name: string;
  family: string;
  summary: string;
  lookAt: string;
  firstTry: string[];
  differs: string;
  values: Values;
  implemented: string[];
  missing: string[];
  refs: string[];
  tags: string[];
  /** 推荐场景（不强制） */
  scene?: string;
  /* ---- 以下是配方图库字段（见上面的说明） ---- */
  short?: string;
  nameEn?: string;
  /** 悬停一句话卖点（≤30 字） */
  pitch?: string;
  category?: RecipeCategory;
  kind?: RecipeKind;
  parent?: string;
  bullets?: RecipeBullet[];
  showcase?: RecipeShowcase;
  neighbors?: string[];
  uiFamilies?: string[];
  uiSkins?: string[];
  games?: string[];
  /** 画面本来就是 2D（横版 / 俯视 / 平面）。「2D」角标和筛选只在它的 2D 展示场景（showcase.scene2d）有构建器时才出现（taxonomy.is2dLive） */
  is2d?: boolean;
  /** 变体远看和父配方几乎一样（缩略图变化 <2% 像素，__gae.gallery.vdiff）：配方卡不放芯片（点了看不出变化），收进「更多」 */
  subtle?: boolean;
  /** 可实现度：不写时，名字带「局部」的算局部，其余算实时（缺口细节只在开发者模式显示） */
  realtime?: 'live' | 'partial';
  overlay?: Values;
}

